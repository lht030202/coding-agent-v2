PRODUCTS: dict[str, Product] = {
    sku: Product(sku, name, Decimal(price), category) for sku, name, price, category in _RAW_PRODUCTS
}


def find_by_sku(sku: str) -> Product:
    """Look up a product; SKUs are matched case-insensitively and surrounding spaces are ignored."""
    try:
        return PRODUCTS[sku.strip().upper()]
    except KeyError:
        raise KeyError(f"unknown SKU: {sku}") from None


def search(query: str) -> list[Product]:
    """Case-insensitive substring search on product names, sorted by name."""
    needle = query.strip().lower()
    if not needle:
        return []
    return sorted((p for p in PRODUCTS.values() if needle in p.name.lower()), key=lambda p: p.name)


def by_category(category: str) -> list[Product]:
    """All products of one category, sorted by SKU."""
    return sorted((p for p in PRODUCTS.values() if p.category == category), key=lambda p: p.sku)


def price_range(low: Decimal, high: Decimal) -> list[Product]:
    """Products priced between low and high, both bounds inclusive, cheapest first."""
    return sorted(
        (p for p in PRODUCTS.values() if low <= p.unit_price < high),
        key=lambda p: (p.unit_price, p.sku),
    )
